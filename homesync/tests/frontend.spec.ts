import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test.use({ launchOptions: { executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' }, viewport: { width: 1440, height: 1000 } })
test.setTimeout(120000)
test('refonte : annonces, analyses, carte persistante, exploration et contrastes', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await mkdir('artifacts', { recursive: true })
  await page.goto(process.env.HOMESYNC_URL ?? 'http://127.0.0.1:5173')
  await page.getByRole('button', { name: 'Commencer ma recherche' }).click()
  await page.waitForFunction(() => (window as any).__hsMap?.getSource('listings'))
  await page.evaluate(() => { (window as any).__initialMap = (window as any).__hsMap })
  await page.getByRole('button', { name: 'Annonces', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Annonces de la recherche' })).toBeVisible()
  await page.getByRole('button', { name: 'Fermer les annonces' }).click()
  await page.locator('textarea').fill('Un T3 à Nantes budget maximum 1200 €')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await page.waitForTimeout(2200)
  await page.getByRole('button', { name: 'Voir la fiche', exact: true }).first().click()
  await page.getByRole('button', { name: 'Favori', exact: true }).last().click()
  await page.getByRole('button', { name: 'Photo suivante' }).click()
  await expect(page.getByRole('img', { name: 'Illustration du logement, photo 2' })).toBeVisible()
  await page.getByRole('button', { name: 'Fermer', exact: true }).click()
  await page.waitForFunction(() => (window as any).__hsMap.areTilesLoaded())
  await page.screenshot({ path: 'artifacts/refonte-desktop.png' })
  await page.getByRole('button', { name: 'Analyses', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Une vue d’ensemble, pour mieux choisir.' })).toBeVisible()
  await expect(page.getByText('4 annonces fictives chargées', { exact: false })).toBeVisible()
  await expect(page.locator('.comparison-scroll tbody tr')).toHaveCount(1)
  await page.screenshot({ path: 'artifacts/refonte-analyses.png' })
  await page.getByRole('button', { name: 'Retour à la recherche' }).click()
  await page.evaluate(() => (window as any).__hsMap.jumpTo({ center: [-1.6, 47.25], zoom: 12.5 }))
  const before = await page.evaluate(() => (window as any).__hsMap.getCenter().toArray())
  await page.locator('textarea').fill('Budget maximum 1100 €')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await page.waitForTimeout(1400)
  expect(await page.evaluate(() => (window as any).__hsMap.getCenter().toArray())).toEqual(before)
  expect(await page.evaluate(() => (window as any).__hsMap === (window as any).__initialMap)).toBe(true)
  const boxes = await page.locator('.hs-price-pin:not([data-hidden="true"]) .pin').evaluateAll(nodes => nodes.map(n => { const r = n.getBoundingClientRect(); return { left: r.left, right: r.right, top: r.top, bottom: r.bottom } }))
  for (let a = 0; a < boxes.length; a++) for (let b = a + 1; b < boxes.length; b++) expect(boxes[a].right <= boxes[b].left || boxes[a].left >= boxes[b].right || boxes[a].bottom <= boxes[b].top || boxes[a].top >= boxes[b].bottom).toBe(true)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => (window as any).__hsMap === (window as any).__initialMap)).toBe(true)
  await expect(page.getByRole('button', { name: 'Ouvrir la conversation' })).toBeVisible()
  await page.getByRole('button', { name: 'Ouvrir la conversation' }).click()
  await expect(page.getByRole('button', { name: 'Microphone indisponible en démonstration' })).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/refonte-mobile-chat.png' })
  await page.locator('textarea').fill('Un T2 à Lyon budget maximum 1200 €')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await page.waitForTimeout(2000)
  await page.getByRole('button', { name: 'Voir la fiche', exact: true }).last().click()
  await expect(page.getByRole('dialog', { name: 'T2 Part-Dieu' })).toBeVisible()
  await page.waitForTimeout(1200)
  await expect(page.getByRole('dialog', { name: 'T2 Part-Dieu' })).toBeVisible()
  await page.screenshot({ path: 'artifacts/refonte-mobile-fiche.png' })
  await page.getByRole('button', { name: 'Fermer', exact: true }).click()
  await page.getByRole('button', { name: 'Analyses', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Une vue d’ensemble, pour mieux choisir.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/refonte-mobile-analyses.png' })
  expect(errors).toEqual([])
  const tokens = await page.evaluate(() => {
    const css = getComputedStyle(document.documentElement)
    return Object.fromEntries(['--navy', '--cream', '--copper-dark', '--surface', '--text', '--text-muted'].map(name => [name, css.getPropertyValue(name).trim()]))
  })
  function luminance(hex: string) {
    const c = hex.replace('#', '').match(/../g)!.map(v => parseInt(v, 16) / 255).map(v => v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4)
    return c[0] * 0.2126 + c[1] * 0.7152 + c[2] * 0.0722
  }
  for (const [foreground, background] of [['--navy', '--surface'], ['--text', '--surface'], ['--text-muted', '--cream'], ['--copper-dark', '--cream']]) {
    const [a, b] = [luminance(tokens[foreground]), luminance(tokens[background])].sort((a, b) => b - a)
    expect((a + 0.05) / (b + 0.05)).toBeGreaterThanOrEqual(4.5)
  }
})

test('mobile société : saisie dans une hauteur réduite et résumé des collaborateurs', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 480 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(process.env.HOMESYNC_URL ?? 'http://127.0.0.1:5173')
  await page.getByRole('button', { name: 'Loger mon équipe' }).click()
  await page.getByRole('button', { name: 'Ouvrir la conversation' }).click()
  const input = page.locator('textarea')
  await input.focus()
  const box = await input.boundingBox()
  expect(box).not.toBeNull()
  expect(box!.y + box!.height).toBeLessThanOrEqual(480)
  await input.fill('Trois logements meublés à Lille pour six collaborateurs pendant quatre mois, budget maximum 1300 € par logement')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await expect(page.locator('.chat-heading')).toContainText('3 logements · 6 personnes · 4 mois')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/refonte-mobile-compact.png' })
})

