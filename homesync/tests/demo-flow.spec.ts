import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test.use({ launchOptions: { executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' } })
test.setTimeout(120000)
const base = process.env.HOMESYNC_URL ?? 'http://127.0.0.1:5173'
for (const example of [
  { name: 'particulier desktop', profile: 'Commencer ma recherche', width: 1440, height: 1000, text: 'Un T3 à Nantes budget maximum 1200 €', count: 4 },
  { name: 'société mobile', profile: 'Loger mon équipe', width: 390, height: 844, text: 'Trois logements meublés à Lille pour six collaborateurs pendant quatre mois, budget maximum 1300 € par logement', count: 6 },
]) {
  test(`parcours démontrable : ${example.name}`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await mkdir('artifacts', { recursive: true })
    await page.setViewportSize({ width: example.width, height: example.height })
    await page.goto(base)
    await page.getByRole('button', { name: example.profile, exact: true }).click()
    await page.waitForFunction(() => (window as any).__hsMap?.getSource('listings'))
    await page.evaluate(() => { (window as any).__demoMap = (window as any).__hsMap })
    if (example.width < 1024) await page.getByRole('button', { name: 'Ouvrir la conversation' }).click()
    await expect(page.getByText('Mode démonstration', { exact: true })).toBeVisible()
    await page.locator('textarea').fill(example.text)
    await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
    await expect.poll(() => page.evaluate(() => (window as any).__hsMap.getSource('listings')._data.features.length), { timeout: 30000 }).toBe(example.count)
    await expect(page.locator('.chat-messages .listing-card').first()).toBeVisible()
    const title = (await page.locator('.chat-messages .listing-card p.font-semibold').first().textContent())!
    await page.getByRole('button', { name: 'Voir la fiche', exact: true }).first().click()
    const sheet = page.getByRole('dialog', { name: title, exact: true })
    await expect(sheet).toBeVisible()
    await expect.poll(() => page.locator('.hs-price-pin[data-selected="true"][data-hidden="false"]').count()).toBe(1)
    await sheet.getByRole('button', { name: 'Favori', exact: true }).click()
    await sheet.getByRole('button', { name: 'Fermer', exact: true }).click()
    await page.getByRole('button', { name: 'Favoris', exact: true }).click()
    const favorites = page.getByRole('dialog', { name: 'Favoris du projet' })
    await expect(favorites).toContainText(title)
    await favorites.getByRole('button', { name: 'Voir la fiche', exact: true }).click()
    await expect(sheet).toBeVisible()
    await sheet.getByRole('button', { name: 'Poser une question', exact: true }).click()
    const messaging = page.getByRole('dialog', { name: 'Messagerie', exact: true })
    await messaging.getByRole('button', { name: 'Préparer une question' }).click()
    await messaging.getByRole('button', { name: 'Valider et envoyer' }).click()
    await expect(messaging.getByText('Réponse simulée', { exact: false })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(messaging).not.toBeVisible()
    await expect(sheet).toBeVisible()
    await sheet.getByRole('button', { name: 'Poser une question', exact: true }).click()
    await expect(messaging.getByText('Réponse simulée', { exact: false })).toBeVisible()
    await page.screenshot({ path: `artifacts/demo-${example.width}-messages.png` })
    await page.keyboard.press('Escape')
    await sheet.getByRole('button', { name: 'Fermer', exact: true }).click()
    await page.waitForFunction(() => (window as any).__hsMap.areTilesLoaded())
    await page.screenshot({ path: `artifacts/demo-${example.width}-carte.png` })
    if (example.width < 1024) await page.getByRole('button', { name: 'Chat', exact: true }).click()
    await page.screenshot({ path: `artifacts/demo-${example.width}-chat.png` })
    await page.getByRole('button', { name: 'Comparer', exact: true }).first().click()
    await page.getByRole('button', { name: 'Comparer', exact: true }).nth(1).click()
    if (example.width < 1024) await page.getByRole('button', { name: 'Réduire le chat' }).click()
    await page.getByRole('button', { name: 'Comparer (2)', exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'Comparer les logements' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `artifacts/demo-${example.width}-comparaison.png` })
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Analyses', exact: true }).click()
    if (example.width < 1024) await expect(page.locator('nav button[aria-current="page"]')).toHaveCount(1)
    expect(await page.evaluate(() => (window as any).__hsMap === (window as any).__demoMap)).toBe(true)
    await page.screenshot({ path: `artifacts/demo-${example.width}-analyses.png` })
    expect(errors).toEqual([])
  })
}

test('erreur de service : garder les résultats et favoris, puis reprendre la recherche', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base)
  await page.getByRole('button', { name: 'Commencer ma recherche' }).click()
  await page.waitForFunction(() => (window as any).__hsMap?.getSource('listings'))
  await page.locator('textarea').fill('Un T3 à Nantes budget maximum 1200 €')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await expect(page.locator('.chat-messages .listing-card').first()).toBeVisible()
  await page.locator('.chat-messages').getByRole('button', { name: 'Favori', exact: true }).first().click()
  await page.evaluate(async () => {
    const { dataServices } = await import('/src/services/index.ts')
    ;(window as any).__originalReply = dataServices.search.reply
    dataServices.search.reply = async () => { throw new Error('Erreur de service provoquée par le test') }
  })
  await page.locator('textarea').fill('Budget maximum 1100 €')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await expect(page.locator('.chat-input-wrap [role="alert"]')).toContainText('Vos critères et favoris sont conservés')
  expect(await page.evaluate(() => (window as any).__hsMap.getSource('listings')._data.features.length)).toBe(4)
  await page.getByRole('button', { name: 'Favoris', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Favoris du projet' }).locator('.listing-card')).toHaveCount(1)
  await page.keyboard.press('Escape')
  await page.evaluate(async () => { const { dataServices } = await import('/src/services/index.ts'); dataServices.search.reply = (window as any).__originalReply })
  await page.locator('textarea').fill('Budget maximum 1100 €')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__hsMap.getSource('listings')._data.features.length)).toBe(3)
  await expect(page.locator('.chat-input-wrap [role="alert"]')).toHaveCount(0)
})

test('une réponse tardive ne remplace pas un projet après changement de profil', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base)
  await page.getByRole('button', { name: 'Commencer ma recherche' }).click()
  await page.waitForFunction(() => (window as any).__hsMap?.getSource('listings'))
  const initialCount = await page.evaluate(() => (window as any).__hsMap.getSource('listings')._data.features.length)
  await page.evaluate(async () => {
    const { dataServices } = await import('/src/services/index.ts')
    const original = dataServices.search.reply
    dataServices.search.reply = request => new Promise(resolve => { (window as any).__finishOldRequest = async () => { resolve(await original(request)) } })
  })
  await page.locator('textarea').fill('Un T3 à Nantes budget maximum 1200 €')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await page.getByRole('button', { name: 'Profil de démonstration' }).click()
  await page.getByRole('button', { name: 'Essayer le profil société' }).click()
  await expect(page.getByRole('button', { name: 'Profil de démonstration' })).toContainText('Société')
  await page.evaluate(async () => { await (window as any).__finishOldRequest() })
  await expect(page.locator('.chat-heading')).toContainText('Logements à préciser')
  await expect(page.getByText('Mise à jour de votre recherche…', { exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).__hsMap.getSource('listings')._data.features.length)).toBe(initialCount)
})
