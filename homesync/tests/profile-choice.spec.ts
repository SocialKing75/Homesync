import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test.use({ launchOptions: { executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' }, viewport: { width: 1440, height: 1000 } })
const base = process.env.HOMESYNC_URL ?? 'http://127.0.0.1:5173'

test('profils : cartes égales, images, clavier, survol et parcours particulier', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await mkdir('artifacts', { recursive: true })
  await page.goto(base)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Votre prochain lieu de viecommence par une conversation.')
  await expect(page.getByText('Recherche 100 % conversationnelle · Toute la France')).toBeVisible()
  expect(await page.locator('.profile-choice').evaluate(node => getComputedStyle(node).backgroundSize)).toBe('cover')
  const photo = await page.request.get(`${base}/home-building.webp`)
  expect(photo.ok()).toBe(true)
  expect((await photo.body()).length).toBeLessThan(200000)
  await page.waitForTimeout(600)
  const cards = await page.locator('.profile-choice-card').evaluateAll(nodes => nodes.map(node => ({ width: node.getBoundingClientRect().width, height: node.getBoundingClientRect().height, y: node.getBoundingClientRect().y })))
  expect(cards[0].width).toBeCloseTo(cards[1].width, 0)
  expect(cards[0].height).toBeCloseTo(cards[1].height, 0)
  expect(await page.locator('.profile-choice-grid').evaluate(n => n.clientWidth)).toBeLessThanOrEqual(960)
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Commencer ma recherche', exact: true })).toBeFocused()
  await page.screenshot({ path: 'artifacts/profiles-desktop-focus.png' })
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Loger mon équipe', exact: true })).toBeFocused()
  await page.locator('.profile-choice-card').first().hover()
  await page.waitForTimeout(250)
  const y = await page.locator('.profile-choice-card').first().evaluate(n => n.getBoundingClientRect().y)
  expect(cards[0].y - y).toBeCloseTo(4, 0)
  await page.mouse.move(0, 0)
  await page.locator('h1').click()
  await page.screenshot({ path: 'artifacts/profiles-desktop.png' })
  await page.getByRole('button', { name: 'Commencer ma recherche' }).click()
  await expect(page.getByRole('status')).toContainText('Profil particulier sélectionné')
  await expect(page.getByRole('button', { name: 'Profil de démonstration' })).toContainText('Particulier')
  expect(errors).toEqual([])
})

