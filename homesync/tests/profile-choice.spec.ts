  await page.goto(base)
  await expect(page.locator('.profile-choice-card')).toHaveCount(2)
  expect(await page.locator('.profile-choice').evaluate(n => getComputedStyle(n).backgroundColor)).toBe('rgb(255, 245, 225)')
